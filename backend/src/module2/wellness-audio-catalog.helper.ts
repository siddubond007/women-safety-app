/**
 * Generates a deterministic, seamless-looping stereo 16-bit PCM WAV buffer for
 * a requested trackId when external Supabase Storage / CDN hosting is not yet
 * populated, ensuring the "Preparing your meditation" download-and-verify flow
 * works reliably in dev, test, and staging without bundling MP3s in the APK.
 */
export function synthesizeDeterministicLoopableWav(
  track: SakhiWellnessAudioTrackMetadata,
  durationSeconds = 4,
): { buffer: Buffer; sha256Checksum: string; mimeType: string; durationSeconds: number } {
  const sampleRate = 16000;
  const numChannels = 2;
  const totalSamples = Math.max(sampleRate, Math.floor(sampleRate * durationSeconds));
  const dataBytes = totalSamples * numChannels * 2;
  const buffer = Buffer.alloc(44 + dataBytes);

  // RIFF WAVE header
  buffer.write("RIFF", 0, "ascii");
  buffer.writeUInt32LE(36 + dataBytes, 4);
  buffer.write("WAVE", 8, "ascii");
  buffer.write("fmt ", 12, "ascii");
  buffer.writeUInt32LE(16, 16); // PCM chunk size
  buffer.writeUInt16LE(1, 20);  // PCM format = 1
  buffer.writeUInt16LE(numChannels, 22);
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(sampleRate * numChannels * 2, 28);
  buffer.writeUInt16LE(numChannels * 2, 32);
  buffer.writeUInt16LE(16, 34); // 16-bit
  buffer.write("data", 36, "ascii");
  buffer.writeUInt32LE(dataBytes, 40);

  const root = track.baseFrequencyHz || 216.0;
  const beatOffset = track.isBinauralLabelled ? 2.0 : 0.25;
  const fadeSamples = Math.min(Math.floor(sampleRate * 0.4), Math.floor(totalSamples / 4));

  for (let i = 0; i < totalSamples; i++) {
    const t = i / sampleRate;
    let env = 1.0;
    if (i < fadeSamples) {
      env = i / fadeSamples;
    } else if (i > totalSamples - fadeSamples) {
      env = (totalSamples - i) / fadeSamples;
    }
    const swell = 0.65 + 0.35 * Math.sin(2 * Math.PI * 0.25 * t);
    const leftVal =
      (0.45 * Math.sin(2 * Math.PI * root * t) +
        0.25 * Math.sin(2 * Math.PI * (root * 1.5) * t) +
        0.12 * Math.sin(2 * Math.PI * (root * 2.0) * t)) *
      swell *
      env;
    const rightVal =
      (0.45 * Math.sin(2 * Math.PI * (root + beatOffset) * t + 0.3) +
        0.25 * Math.sin(2 * Math.PI * (root * 1.5) * t + 0.3) +
        0.12 * Math.sin(2 * Math.PI * (root * 2.0) * t + 0.3)) *
      swell *
      env;

    const pcmL = Math.max(-24000, Math.min(24000, Math.round(leftVal * 12000)));
    const pcmR = Math.max(-24000, Math.min(24000, Math.round(rightVal * 12000)));
    const offset = 44 + i * 4;
    buffer.writeInt16LE(pcmL, offset);
    buffer.writeInt16LE(pcmR, offset + 2);
  }

  const sha256Checksum = createHash("sha256").update(buffer).digest("hex");
  return {
    buffer,
    sha256Checksum,
    mimeType: "audio/wav",
    durationSeconds,
  };
}

