export function selectNonRepeatingRandomTrack(
  category?: string,
  excludeTrackId?: string | null,
): SakhiWellnessAudioTrackMetadata {
  const pool = SAKHI_42_WELLNESS_TRACKS.filter((t) =>
    !category || category === "ALL" ? true : t.category === category,
  );
  const candidates = pool.filter((t) => t.trackId !== excludeTrackId);
  const effective = candidates.length > 0 ? candidates : (pool.length > 0 ? pool : SAKHI_42_WELLNESS_TRACKS);
  return effective[0]!;
}
